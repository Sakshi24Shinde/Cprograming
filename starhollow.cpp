#include <stdio.h>

int main()
{
    int i, j;

    for(i = 1; i <= 11; i++)
    {
        for(j = 1; j <= 13; j++)
        {
            if((i <= 2 && j >= 5 && j <= 8) ||
               (i == 3 && (j == 4 || j == 9)) ||
               (i == 4 && (j == 3 || j == 10)) ||
               (i == 5 && (j == 2 || j == 11)) ||
               (i >= 6 && i <= 7 && (j == 1 || j == 12)) ||
               (i == 8 && (j == 2 || j == 11)) ||
               (i == 9 && (j == 3 || j == 10)) ||
               (i >= 10 && j >= 4 && j <= 8))
            {
                printf("* ");
            }
            else
            {
                printf("  ");
            }
        }
        printf("\n");
    }

    return 0;
}